// errorResponse mirrors the common error format.
type errorResponse struct {
	Error struct {
		Code    string             `json:"code"`
		Message string             `json:"message"`
		Details []model.FieldError `json:"details"`
		TraceID string             `json:"trace_id"`
	} `json:"error"`
}

// taskControllerFixture holds everything a test needs: the subject under test and the mocks it depends on.
// When the controller gains a dependency, add a field here; the tests themselves do not change.
type taskControllerFixture struct {
	mockCtrl   *gomock.Controller
	service    *mocks.MockTaskService
	controller *TaskController // subject under test
}

// setUp is called at the start of each test's Arrange step: it creates the mocks and injects them into the controller under test.
// The mocks are generated by mockgen from service.TaskService (see the go:generate line in task_service.go).
// A test that sets no EXPECT() fails if the service is called at all,
// so "invalid input must not reach the service" is verified automatically.
func setUp(t *testing.T) *taskControllerFixture {
	t.Helper()
	mockCtrl := gomock.NewController(t)
	f := &taskControllerFixture{
		mockCtrl: mockCtrl,
		service:  mocks.NewMockTaskService(mockCtrl),
	}
	f.controller = NewTaskController(f.service, dto.NewValidator(), slog.New(slog.DiscardHandler))
	t.Cleanup(f.tearDown) // always runs when the test ends, even after t.Fatal
	return f
}

// tearDown verifies that every EXPECT() was met (arguments and call counts); otherwise the test fails.
func (f *taskControllerFixture) tearDown() {
	f.mockCtrl.Finish()
}

// serve calls a controller method directly, without the router.
// The router would put {id} into the request; SetPathValue simulates that. An empty id means the route has no {id}.
func serve(t *testing.T, h http.HandlerFunc, id, body string) *httptest.ResponseRecorder {
	t.Helper()
	req := httptest.NewRequest(http.MethodPost, "/", strings.NewReader(body))
	req.Header.Set("Content-Type", "application/json")
	if id != "" {
		req.SetPathValue("id", id)
	}
	rec := httptest.NewRecorder()
	h(rec, req)
	return rec
}

func decodeError(t *testing.T, rec *httptest.ResponseRecorder) errorResponse {
	t.Helper()
	assert.Equal(t, "application/json", rec.Header().Get("Content-Type"))
	var resp errorResponse
	require.NoError(t, json.Unmarshal(rec.Body.Bytes(), &resp), "body: %s", rec.Body.String())
	return resp
}

// assertError checks the HTTP status and the error code.
func assertError(t *testing.T, rec *httptest.ResponseRecorder, wantStatus int, wantCode string) {
	t.Helper()
	require.Equal(t, wantStatus, rec.Code, "body: %s", rec.Body.String())
	assert.Equal(t, wantCode, decodeError(t, rec).Error.Code)
}

// ---------- List ----------

func TestList_NoTasks_ReturnsEmptyArray(t *testing.T) {
	// Arrange
	f := setUp(t)
	f.service.EXPECT().List(gomock.Any()).Return([]model.Task{}, nil)

	// Act
	rec := serve(t, f.controller.List, "", "")

	// Assert
	require.Equal(t, http.StatusOK, rec.Code)
	// an empty list must be [] rather than null, which is easier for clients
	assert.JSONEq(t, `{"result":[]}`, rec.Body.String())
}

// Unexpected errors return 500 and must not leak the original error message to the client.
func TestList_UnexpectedServiceError_Returns500WithoutLeakingDetails(t *testing.T) {
	// Arrange
	f := setUp(t)
	f.service.EXPECT().List(gomock.Any()).Return(nil, errors.New("db password is hunter2"))

	// Act
	rec := serve(t, f.controller.List, "", "")

	// Assert
	assertError(t, rec, http.StatusInternalServerError, "INTERNAL_ERROR")
	assert.NotContains(t, rec.Body.String(), "hunter2", "internal error message leaked to client")
}

